const fs = require('fs'), path = require('path'), assert = require('assert/strict')
const { chromium } = require('./playwright-runtime.cjs')
const report = { started: new Date().toISOString(), mode: 'Headless functional browser check, not foreground performance or screen-reader certification', checks: [], errors: [] }
const output = path.join(__dirname, 'gap-engineering-workflows.json')
let browser, page
;(async () => {
  browser = await chromium.launch({ channel: 'chrome', headless: true })
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('pageerror', error => report.errors.push(error.message))
  const submitted = []
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/(simulations|eruption-sequences)$/.test(request.url())) submitted.push({ path: new URL(request.url()).pathname, body: request.postDataJSON() }) })
  await page.goto('http://127.0.0.1:8000/')
  await page.getByRole('button', { name: 'Run simulation', exact: true }).waitFor()
  report.assets = await page.locator('script[src]').evaluateAll(elements => elements.map(element => element.src))
  await page.getByText('Screening & population', { exact: true }).click()
  await page.getByRole('combobox', { name: /^Population year/ }).click()
  await page.getByRole('option', { name: '2020 · historical reporting', exact: true }).click()
  await page.getByRole('combobox', { name: /^Screening conditions/ }).click()
  await page.getByRole('option', { name: /^Dry ash/ }).click()
  await page.getByRole('button', { name: 'Run simulation', exact: true }).click()
  await page.getByRole('button', { name: 'Play sequence', exact: true }).waitFor({ timeout: 120000 })
  assert.equal(submitted[0].body.population_year, 2020)
  assert.equal(submitted[0].body.screening_context.ash_condition, 'dry')
  assert.deepEqual(submitted[1].body.simulation, submitted[0].body)
  report.checks.push({ name: 'Grid and finite sequence submit matching screening and census context', passed: true, requests: submitted })
  await page.getByText('Location table & exports', { exact: true }).click()
  assert.match(await page.locator('.result-table-disclosure').innerText(), /unknown/i)
  await page.getByRole('combobox', { name: /^Population year/ }).click()
  await page.getByRole('option', { name: '2024 · current scenarios', exact: true }).click()
  await page.getByRole('combobox', { name: /^Screening conditions/ }).click()
  await page.getByRole('option', { name: /^Wet ash/ }).click()
  assert.match(await page.locator('.stale-message').innerText(), /last completed simulation/)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Scenario JSON', exact: true }).click()
  const download = await downloadPromise
  const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
  assert.equal(exported.population_year, 2020)
  assert.equal(exported.screening_context.ash_condition, 'dry')
  fs.writeFileSync(path.join(__dirname, 'gap-engineering-workflow-scenario.json'), JSON.stringify(exported, null, 2))
  report.checks.push({ name: 'Stale edits do not rewrite last-completed scenario export', passed: true, exported_context: exported.screening_context, exported_population_year: exported.population_year })
  await page.getByRole('button', { name: 'Taal 2020', exact: true }).click()
  await page.getByRole('button', { name: 'Check historical reference', exact: true }).click()
  await page.getByText('Derived reference contours & digitization uncertainty', { exact: true }).waitFor({ timeout: 30000 })
  await page.getByText('Derived reference contours & digitization uncertainty', { exact: true }).click()
  await page.locator('.historical-reference-map svg path').first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'Trace GeoJSON', exact: true }).count(), 2)
  assert.equal(await page.getByRole('button', { name: 'Inspect historical result', exact: true }).count(), 0)
  assert.match(await page.locator('.historical-evaluation').innerText(), /not independent observations or model predictions/)
  await page.screenshot({ path: path.join(__dirname, 'gap-engineering-historical-reference.png'), fullPage: true })
  const referenceDownloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Trace GeoJSON', exact: true }).first().click()
  const referenceDownload = await referenceDownloadPromise
  const geojson = JSON.parse(fs.readFileSync(await referenceDownload.path(), 'utf8'))
  assert.equal(geojson.type, 'Feature')
  report.checks.push({ name: 'Both derived contours render and export while blocked prediction/validation remains explicit', passed: true, exported_geojson_type: geojson.type, map_path_count: await page.locator('.historical-reference-map svg path').count() })
  report.completed = true
  report.finished = new Date().toISOString()
  fs.writeFileSync(output, JSON.stringify(report, null, 2))
  await browser.close()
})().catch(async error => { report.completed = false; report.errors.push(error.stack); if (page && !page.isClosed()) report.failure_snapshot = await page.locator('body').ariaSnapshot(); fs.writeFileSync(output, JSON.stringify(report, null, 2)); console.error(error); await browser?.close(); process.exitCode = 1 })
