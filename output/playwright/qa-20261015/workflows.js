async (page) => {
  const report = { cases: [], errors: [], responses: [] }
  const check = (name, ok, detail) => { report.cases.push({ name, pass: !!ok, detail }); if (!ok) throw new Error(name + ': ' + JSON.stringify(detail)) }
  page.on('pageerror', error => report.errors.push(String(error)))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:8066')
  await page.getByRole('button', { name: 'Run simulation' }).waitFor()
  const simulationResponse = page.waitForResponse(r => r.url().endsWith('/api/simulations'))
  const sequenceResponse = page.waitForResponse(r => r.url().endsWith('/api/eruption-sequences'))
  await page.getByRole('button', { name: 'Run simulation' }).click()
  const simulation = await (await simulationResponse).json()
  const sequence = await (await sequenceResponse).json()
  await page.getByRole('slider', { name: 'Eruption timeline' }).waitFor()
  check('real calculation and sequence', simulation.receptors.length === 320 && sequence.frames.length >= 25, { receptors: simulation.receptors.length, frames: sequence.frames.length })
  check('same submitted scenario', JSON.stringify(simulation.scenario) === JSON.stringify(sequence.scenario))
  check('default paused', await page.getByRole('button', { name: 'Play sequence' }).isVisible())
  await page.getByRole('button', { name: 'During', exact: true }).click()
  check('during stage seek', await page.getByRole('button', { name: 'During', exact: true }).getAttribute('aria-pressed') === 'true')
  await page.getByRole('button', { name: 'Play sequence' }).click()
  await page.waitForTimeout(1600)
  await page.getByRole('button', { name: 'Pause sequence' }).click()
  check('replay and pause', Number(await page.getByRole('slider').inputValue()) > 0)
  await page.getByRole('slider').fill(String(sequence.frames.length - 1))
  const integrated = simulation.grid.load_kg_m2.flat().reduce((sum, n) => sum + n, 0) * simulation.grid.cell_m ** 2
  check('final mass agreement', Math.abs(sequence.frames.at(-1).diagnostics.inside_domain_mass_kg - integrated) <= Math.max(1e-6, integrated * 1e-12))
  await page.getByText('Location table & exports', { exact: true }).click()
  const csvEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Final CSV', exact: true }).click()
  await (await csvEvent).saveAs('output/playwright/qa-20261015/default.csv')
  const jsonEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Scenario JSON', exact: true }).click()
  await (await jsonEvent).saveAs('output/playwright/qa-20261015/default-scenario.json')
  report.cases.push({ name: 'CSV and scenario downloads', pass: true })
  await page.getByLabel('Wind FROM (° clockwise from N)').fill('90')
  check('stale notice', await page.getByText(/Parameters have changed/).isVisible())
  await page.route('**/api/simulations', route => route.abort())
  await page.getByRole('button', { name: 'Run simulation' }).click()
  await page.getByRole('alert').waitFor()
  check('network failure preserves results', await page.getByRole('heading', { name: 'Municipal and facility exposure' }).isVisible())
  await page.unroute('**/api/simulations')
  await page.getByRole('button', { name: 'Wind sweep', exact: true }).click()
  const sweepResponse = page.waitForResponse(r => r.url().endsWith('/api/wind-sweeps'))
  await page.getByRole('button', { name: 'Evaluate all wind directions' }).click()
  const sweep = await (await sweepResponse).json()
  await page.getByRole('button', { name: 'Use this direction' }).first().waitFor()
  check('default catalog sweep succeeds', sweep.receptors?.length === 320, { count: sweep.receptors?.length, detail: sweep.detail })
  await page.getByRole('button', { name: 'Taal 2020', exact: true }).click()
  const historicalResponse = page.waitForResponse(r => r.url().endsWith('/api/replications/taal-2020'))
  await page.getByRole('button', { name: 'Check historical reference' }).click()
  const historical = await (await historicalResponse).json()
  check('historical remains unavailable honestly', historical.available === false && historical.simulation == null)
  await page.screenshot({ path: 'output/playwright/qa-20261015/historical-light.png', fullPage: true })
  await page.getByRole('button', { name: 'Simulation', exact: true }).click()
  await page.getByRole('button', { name: 'Dark theme' }).click()
  await page.screenshot({ path: 'output/playwright/qa-20261015/desktop-dark.png' })
  await page.setViewportSize({ width: 320, height: 900 })
  check('320px dark no document overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth })))
  await page.screenshot({ path: 'output/playwright/qa-20261015/mobile-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Light theme' }).click()
  check('320px light no document overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: 'output/playwright/qa-20261015/mobile-light.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('combobox', { name: /^Scenario / }).focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  check('keyboard chooses Mayon', (await page.getByRole('combobox', { name: /^Scenario / }).innerText()).includes('Mayon'))
  await page.getByRole('button', { name: 'Run simulation' }).click()
  await page.getByText(/Mayon result/).waitFor()
  await page.getByRole('button', { name: 'During', exact: true }).click()
  await page.screenshot({ path: 'output/playwright/qa-20261015/mayon-light.png' })
  check('Mayon real ash and lava workflow', await page.getByRole('slider', { name: 'Eruption timeline' }).isVisible())
  check('no JavaScript exceptions', report.errors.length === 0, report.errors)
  console.log(JSON.stringify(report, null, 2))
  return report
}
